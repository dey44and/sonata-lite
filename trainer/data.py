"""Single-keyframe SSL data loading, packing, and explicit-step batch planning.

The existing NumPy augmentation pipeline runs in DataLoader workers. The sampler
attaches the optimizer step to each requested sample, so prefetching cannot move
the masking schedule ahead of the batch it belongs to.
"""

from __future__ import annotations

import random
from collections.abc import Mapping, Sequence

import numpy as np
import torch
from torch.utils.data import Dataset, Sampler

from augmentation import NuScenesSSLViews
from datasets import NuScenesKeyframeReader
from datasets._json import iter_json_records


class NuScenesSSLDataset(Dataset):
    """Read a fresh scan and generate its teacher/student views on CPU.

    ``(index, step)`` requests are generated by :class:`StepBatchSampler`.
    Augmentation randomness depends only on ``seed, step, index``; worker count
    and prefetch order therefore do not change a planned batch or a resumed run.
    Plain integer requests use step zero, which is useful for inspecting samples.

    ``split=None`` selects all available scenes. Training configurations should
    request an official training split or an explicit list of ``scene_names``.
    """

    def __init__(
        self,
        dataroot,
        *,
        version="v1.0-mini",
        augmentation=None,
        scene_names: Sequence[str] | None = None,
        split: str | None = None,
        seed=42,
        max_samples: int | None = None,
    ):
        self.reader = NuScenesKeyframeReader(dataroot, version=version)
        self.seed = int(seed)
        if self.seed < 0:
            raise ValueError("seed must be nonnegative")
        if augmentation is None:
            augmentation = NuScenesSSLViews()
        elif isinstance(augmentation, Mapping):
            augmentation = NuScenesSSLViews(**augmentation)
        self.augmentation = augmentation

        if scene_names is not None and split is not None:
            raise ValueError("select either scene_names or split")
        if split is not None:
            expected_version = {
                "mini_train": "v1.0-mini",
                "mini_val": "v1.0-mini",
                "train": "v1.0-trainval",
                "val": "v1.0-trainval",
                "test": "v1.0-test",
            }
            if split not in expected_version:
                raise ValueError(f"unsupported nuScenes split: {split!r}")
            if version != expected_version[split]:
                raise ValueError(f"split {split!r} requires {expected_version[split]!r}")
            try:
                from nuscenes.utils.splits import create_splits_scenes
            except ImportError as error:
                raise ImportError(
                    "Official split selection requires nuscenes-devkit; "
                    "alternatively provide explicit scene_names."
                ) from error
            scene_names = create_splits_scenes(verbose=False)[split]

        selected_scenes = None
        if scene_names is not None:
            requested = set(scene_names)
            scenes = list(iter_json_records(self.reader.dataroot / version / "scene.json"))
            available = {scene["name"] for scene in scenes}
            missing = requested - available
            if missing:
                raise ValueError(f"requested scenes are absent from {version}: {sorted(missing)}")
            selected_scenes = {
                scene["token"] for scene in scenes if scene["name"] in requested
            }
        self.sample_tokens = tuple(
            token
            for token, frame in self.reader._keyframes.items()
            if selected_scenes is None or frame.scene_token in selected_scenes
        )
        if max_samples is not None:
            if max_samples <= 0:
                raise ValueError("max_samples must be positive")
            self.sample_tokens = self.sample_tokens[:max_samples]
        if not self.sample_tokens:
            raise ValueError("no LIDAR_TOP keyframes remain after scene selection")

    def __len__(self):
        return len(self.sample_tokens)

    def __getitem__(self, request):
        index, step = request if isinstance(request, tuple) else (request, 0)
        index, step = int(index), int(step)
        if index < 0 or index >= len(self):
            raise IndexError(index)
        if step < 0:
            raise ValueError("training step must be nonnegative")
        item = self.reader.read(self.sample_tokens[index])
        # The existing transforms use both module-level RNGs. Restore them after
        # the call so reading a sample cannot change training-process randomness
        # when num_workers=0, or perturb unrelated work in a worker.
        numpy_state, python_state = np.random.get_state(), random.getstate()
        seeds = np.random.SeedSequence([self.seed, step, index]).generate_state(3)
        try:
            np.random.seed(int(seeds[0]))
            random.seed((int(seeds[1]) << 32) | int(seeds[2]))
            schedule = self.augmentation.mask_generator.mask_schedule
            views = self.augmentation(item, step=step if schedule is not None else None)
        finally:
            np.random.set_state(numpy_state)
            random.setstate(python_state)
        views["training_step"] = step
        return views


class StepBatchSampler(Sampler):
    """Shuffle epochs and attach the actual training step to every sample.

    Resume with ``start_step``: epoch permutations are recreated directly from
    ``seed, epoch`` without iterating through earlier training steps. A final
    short batch is kept unless ``drop_last=True``.
    """

    def __init__(
        self,
        dataset_size,
        batch_size,
        total_steps,
        *,
        seed=42,
        start_step=0,
        drop_last=False,
    ):
        if dataset_size <= 0 or batch_size <= 0:
            raise ValueError("dataset_size and batch_size must be positive")
        if total_steps < 0 or not 0 <= start_step <= total_steps:
            raise ValueError("require 0 <= start_step <= total_steps")
        self.dataset_size = int(dataset_size)
        self.batch_size = int(batch_size)
        self.total_steps = int(total_steps)
        self.seed = int(seed)
        self.start_step = int(start_step)
        self.drop_last = bool(drop_last)
        self.batches_per_epoch = (
            self.dataset_size // self.batch_size
            if self.drop_last
            else (self.dataset_size + self.batch_size - 1) // self.batch_size
        )
        if not self.batches_per_epoch:
            raise ValueError("drop_last would discard the entire dataset")

    def __len__(self):
        return self.total_steps - self.start_step

    def __iter__(self):
        cached_epoch, order = None, None
        for step in range(self.start_step, self.total_steps):
            epoch, batch_index = divmod(step, self.batches_per_epoch)
            if epoch != cached_epoch:
                order = np.random.default_rng(
                    np.random.SeedSequence([self.seed, epoch])
                ).permutation(self.dataset_size)
                cached_epoch = epoch
            start = batch_index * self.batch_size
            yield [(int(index), step) for index in order[start : start + self.batch_size]]


def seed_worker(worker_id):
    """Seed NumPy and Python from PyTorch's per-worker seed."""
    del worker_id
    worker_seed = torch.initial_seed() % (2**32)
    np.random.seed(worker_seed)
    random.seed(worker_seed)


def _pack_views(views, *, masked=False):
    if not views:
        return None
    grid_size = float(views[0]["grid_size"])
    if any(float(view["grid_size"]) != grid_size for view in views):
        raise ValueError("all views in a packed group must use the same grid_size")
    lengths = [len(view["coord"]) for view in views]
    if any(length == 0 for length in lengths):
        raise ValueError("cannot pack an empty view")
    dtypes = {
        "coord": np.float32,
        "origin_coord": np.float32,
        "feat": np.float32,
        "grid_coord": np.int64,
    }
    if masked:
        dtypes["mask"] = np.bool_
    packed = {
        key: torch.from_numpy(
            np.ascontiguousarray(np.concatenate([view[key] for view in views]), dtype=dtype)
        )
        for key, dtype in dtypes.items()
    }
    packed["offset"] = torch.from_numpy(np.cumsum(lengths, dtype=np.int64))
    packed["grid_size"] = grid_size
    return packed


def collate_ssl_views(samples):
    """Pack variable-length crops in scene-major, then view-major order.

    Each offset entry marks one crop, not one original scan. Diagnostic arrays
    such as patch IDs and intensity (already contained in ``feat``) are omitted.
    ``local`` is ``None`` when local_view_num is zero.
    """
    if not samples:
        raise ValueError("cannot collate an empty batch")
    step = int(samples[0]["training_step"])
    if any(int(sample["training_step"]) != step for sample in samples):
        raise ValueError("all samples in a batch must have the same training step")
    source_keys = {
        "global": "global_views",
        "masked_global": "masked_global_views",
        "local": "local_views",
    }
    counts = {name: len(samples[0][key]) for name, key in source_keys.items()}
    if not counts["global"] or counts["masked_global"] != counts["global"]:
        raise ValueError("require nonempty globals and one masked view per global")
    result = {}
    for name, key in source_keys.items():
        if any(len(sample[key]) != counts[name] for sample in samples):
            raise ValueError(f"inconsistent {key} count within batch")
        result[name] = _pack_views(
            [view for sample in samples for view in sample[key]],
            masked=name == "masked_global",
        )
    result.update(
        meta=[sample["meta"] for sample in samples],
        step=step,
        batch_size=len(samples),
        view_counts=counts,
    )
    return result
