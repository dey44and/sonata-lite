"""Spatial self-distillation primitives adapted from the official Sonata code.

Source: Pointcept, ``sonata_v1m1_base.py`` file
"""

from typing import NamedTuple

import torch
import torch.distributed as dist
from torch.nn import functional as F


def _distributed():
    # Check if distributed computing is available
    return dist.is_available() and dist.is_initialized()


@torch.no_grad()
def sinkhorn_knopp(scores, temperature, num_iter: int = 3):
    """Balance selected teacher score rows, including across distributed ranks.

    Returns FP32 assignments of shape [local_rows, prototypes]. Each row sums
    to one. A shared logit shift and a tiny positive floor prevent overflow/zero
    divisions without changing the intended normalization objective.

    :param scores: The tensor containing the output scores generated by the cluster.
    :param temperature: The temperature parameter (works similarly as with softmax).
    :param num_iter: The total number of iterations.
    """
    if scores.ndim != 2 or scores.shape[1] == 0:
        raise ValueError("Sinkhorn expects [rows, prototypes] scores")
    if temperature <= 0 or num_iter < 1:
        raise ValueError("temperature and num_iter must be positive")
    # First we divide by temperature
    values = scores.detach().float() / temperature

    # We count the total number of voxels, and return the actual values if there are none elements.
    count = torch.tensor(values.shape[0], device=values.device, dtype=torch.long)
    if _distributed():
        dist.all_reduce(count)
    n = int(count.item())
    if n == 0:
        return values

    # We get the maximum value and subtract it from each value.
    maximum = values.max() if values.numel() else values.new_tensor(-float("inf"))
    if _distributed():
        dist.all_reduce(maximum, op=dist.ReduceOp.MAX)
    tiny = torch.finfo(torch.float32).tiny
    q = (values - maximum).exp().clamp_min_(tiny).t()

    # Then we divide the entire tensor by the total sum.
    total = q.sum()
    if _distributed():
        dist.all_reduce(total)
    q /= total

    # For each iteration, we compute the sum for each row, divide each row by its corresponding sum
    # then we do similarly with each column.
    k = q.shape[0]
    for _ in range(num_iter):
        row_mass = q.sum(dim=1, keepdim=True)
        if _distributed():
            dist.all_reduce(row_mass)
        q = q / row_mass.clamp_min(tiny) / k
        q = q / q.sum(dim=0, keepdim=True).clamp_min(tiny) / n

    # At the end, we multiply each value by n and apply again the transpose.
    return (q * n).t().contiguous()


def up_cast(point, levels: int = 2):
    """Gather coarse features onto each pooling parent, then concatenate.
    LitePT-S defaults produce 504 -> 756 -> 900 channels.

    :param point: A dictionary containing the features resulted from the backbone.
    :param levels: The number of upcasts the function should apply.
    """
    for _ in range(levels):
        if "pooling_parent" not in point or "pooling_inverse" not in point:
            raise ValueError("up_cast requires a traceable encoder pooling hierarchy")
        parent = point["pooling_parent"]
        parent["feat"] = torch.cat(
            [parent["feat"], point["feat"][point["pooling_inverse"].long()]], dim=-1
        )
        if "sparse_conv_feat" in parent:
            parent["sparse_conv_feat"] = parent["sparse_conv_feat"].replace_feature(
                parent["feat"]
            )
        point = parent
    return point


