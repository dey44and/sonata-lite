@torch.no_grad()
def match_nearest(
    student_coord,
    student_offset,
    teacher_coord,
    teacher_offset,
    teacher_view_for_student,
    radius,
    query_chunk_size: int = 1024,
    reference_chunk_size: int = 4096,
):
    """Return ([student_index, teacher_index] pairs, student view indices).

    ``teacher_view_for_student[v]`` selects the teacher view paired with
    student view v. Packed offsets delimit views and prevent cross-scene
    matches. Coordinates must be in the shared, original scene frame.
    Strict distance < radius follows Sonata. Temporary distance matrices are
    bounded by query_chunk_size * reference_chunk_size, rather than N * M.
    """
    if radius <= 0 or query_chunk_size < 1 or reference_chunk_size < 1:
        raise ValueError("radius and matching chunk sizes must be positive")
    student_ends = [0] + student_offset.detach().cpu().tolist()
    teacher_ends = [0] + teacher_offset.detach().cpu().tolist()
    if len(teacher_view_for_student) != len(student_ends) - 1:
        raise ValueError("one teacher view index is required for each student view")
    pairs, views = [], []
    for view, teacher_view in enumerate(teacher_view_for_student):
        if not 0 <= teacher_view < len(teacher_ends) - 1:
            raise ValueError("teacher view index is outside the packed teacher batch")
        first, last = student_ends[view : view + 2]
        teacher_first, teacher_last = teacher_ends[teacher_view : teacher_view + 2]
        if first == last or teacher_first == teacher_last:
            continue
        for start in range(first, last, query_chunk_size):
            end = min(start + query_chunk_size, last)
            query = student_coord[start:end].float()
            best_distance = query.new_full((len(query),), float("inf"))
            best_index = torch.zeros(len(query), device=query.device, dtype=torch.long)
            for reference_start in range(teacher_first, teacher_last, reference_chunk_size):
                reference_end = min(reference_start + reference_chunk_size, teacher_last)
                # The direct Euclidean kernel avoids cancellation near identical
                # coordinates that can occur in the matrix-multiplication path.
                distances = torch.cdist(
                    query,
                    teacher_coord[reference_start:reference_end].float(),
                    compute_mode="donot_use_mm_for_euclid_dist",
                )
                distance, index = distances.min(dim=1)
                closer = distance < best_distance
                best_distance = torch.where(closer, distance, best_distance)
                best_index = torch.where(closer, index + reference_start, best_index)
            valid = best_distance < radius
            student_index = torch.arange(start, end, device=query.device)[valid]
            pairs.append(torch.stack([student_index, best_index[valid]], dim=1))
            views.append(torch.full_like(student_index, view))
    if not pairs:
        return (
            torch.empty((0, 2), device=student_coord.device, dtype=torch.long),
            torch.empty(0, device=student_coord.device, dtype=torch.long),
        )
    return torch.cat(pairs), torch.cat(views)


# A tuple defined for storing the loss results
class DistillationResult(NamedTuple):
    loss: torch.Tensor
    matched: torch.Tensor
    matched_views: torch.Tensor


def matched_distillation_loss(
    student_scores,
    teacher_scores,
    student_point,
    teacher_point,
    teacher_view_for_student,
    *,
    teacher_temp,
    student_temp=0.1,
    match_max_r=0.32,
    sinkhorn_iterations=3,
    query_chunk_size=1024,
    reference_chunk_size=4096,
):
    """Match first, balance the gathered teacher rows, then average per view.

    Repeated teacher matches intentionally appear repeatedly in Sinkhorn.
    Empty view pairs contribute no direct supervision and are excluded from
    the view average. A completely empty branch returns a differentiable zero.
    DDP scaling averages over valid views globally, even if ranks have unequal
    match counts. Returned match metrics describe this rank's rows/views.
    """
    if student_temp <= 0:
        raise ValueError("student_temp must be positive")
    # We find the nearest pair for each student voxel.
    pairs, view_index = match_nearest(
        student_point["origin_coord"],
        student_point["offset"],
        teacher_point["origin_coord"],
        teacher_point["offset"],
        teacher_view_for_student,
        match_max_r,
        query_chunk_size,
        reference_chunk_size,
    )
    # We apply the Sinkhorn-Knopp algorithm on teacher prototypes.
    targets = sinkhorn_knopp(
        teacher_scores[pairs[:, 1]], teacher_temp, num_iter=sinkhorn_iterations
    )
    # We apply the softmax activation on student prototypes.
    per_row = -(
        targets * F.log_softmax(student_scores[pairs[:, 0]].float() / student_temp, dim=-1)
    ).sum(dim=-1)
    num_views = len(teacher_view_for_student)
    counts = torch.bincount(view_index, minlength=num_views)
    totals = student_scores.new_zeros(num_views, dtype=torch.float32).index_add(
        0, view_index, per_row
    )
    valid = counts > 0
    local_views = valid.sum()
    global_views = local_views.detach().clone()
    world_size = 1
    if _distributed():
        dist.all_reduce(global_views)
        world_size = dist.get_world_size()
    # Keep an autograd path through every enabled student branch even when
    # this rank has no matched rows (important for DDP and empty crops).
    loss = (totals[valid] / counts[valid]).sum() + student_scores.sum() * 0.0
    if global_views.item():
        loss = loss * world_size / global_views
    return DistillationResult(loss, counts.sum().detach(), local_views.detach())
